const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Store = require('../relay-server/world-store');
const filename = path.join(__dirname, 'store-fixture', 'world.json');
let state = { revision: 1, meta: { width: 500 }, objects: Array.from({ length: 1000 }, (_, i) => ({ id: i, text: 'ore' })) };
let failures = [];
const store = new Store(fs, filename, () => state, msg => failures.push(msg));
(async () => {
    store.markDirty();
    const firstTimer = store.timer;
    for (let i = 0; i < 100; i++) store.markDirty();
    assert.equal(store.timer, firstTimer, '100 edits share one scheduled write');
    clearTimeout(store.timer); store.timer = null;
    let heartbeats = 0;
    const heartbeat = setInterval(() => heartbeats++, 1);
    await store.flush(); clearInterval(heartbeat);
    assert.deepEqual(JSON.parse(fs.readFileSync(filename)), state);
    assert.ok(heartbeats > 0, 'saving yields to event loop');
    const oldText = fs.readFileSync(filename, 'utf8');
    state = { revision: 2, objects: [{ bad: 1n }] }; store.dirty = true;
    await store.flush(); clearTimeout(store.timer); store.timer = null;
    assert.equal(fs.readFileSync(filename, 'utf8'), oldText, 'failed serialization preserves last save');
    assert.equal(failures.length, 1);
    state = { revision: 3, objects: [{ id: 'recovered' }] };
    await store.flush();
    assert.deepEqual(JSON.parse(fs.readFileSync(filename)), state);
    console.log('PASS: debounced asynchronous compact save, responsive event loop, atomic replacement and failure recovery. Fixture only.');
})().catch(err => { console.error(err); process.exitCode = 1; });
