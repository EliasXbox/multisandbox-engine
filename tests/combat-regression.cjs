const assert = require('node:assert/strict');
const Combat = require('../relay-server/combat');
const World = require('../relay-server/world-state');
const world = new World(); world.meta.world_epoch = 20;
world.setPlayer({id: 'MINECRAFT:steve', x: 10, z: 10});
world.setPlayer({id: 'MINDUSTRY:host', x: 12, z: 10, life_id: 'life-2'});
const sent = [], queued = [];
const combat = new Combat(world, (game, packet) => sent.push(packet), (game, packet) => queued.push(packet),
    (x, y) => ({x, z: y}), angle => angle);
combat.frame({seq: 1, units: [{id: 'UNIT:3', x: 11, y: 10, health_fraction: .5, rotation: 90}]});
assert.equal(sent.length, 1); assert.equal(sent[0].units[0].health_fraction, .5);
combat.frame({seq: 1, units: []}); assert.equal(sent.length, 1, 'late frame must not erase current units');
combat.frame({seq: NaN, units: []}); assert.equal(sent.length, 1);
combat.hit({player_id: 'steve', target_id: 'UNIT:3', amount_fraction: .2});
assert.equal(queued.at(-1).amount_fraction, .2);
combat.hit({player_id: 'steve', target_id: 'UNIT:3', amount_fraction: .2});
assert.equal(queued.length, 1, 'duplicate rapid hit is throttled');
combat.hit({player_id: 'steve', target_id: 'MINDUSTRY:host', amount_fraction: .1, life_id: 'untrusted'});
assert.equal(queued.at(-1).life_id, 'life-2', 'authoritative target life comes from host');
for (const amount_fraction of [NaN, -1, 2]) combat.hit({player_id: 'steve', target_id: 'UNIT:3', amount_fraction});
combat.hit({player_id: 'unknown', target_id: 'UNIT:3', amount_fraction: .1});
assert.equal(queued.length, 2);
world.players.get('MINECRAFT:steve').x = 99;
combat.hit({player_id: 'steve', target_id: 'MINDUSTRY:host', amount_fraction: .2});
assert.equal(queued.length, 2, 'remote attacks out of reach are rejected');
combat.localHealth({player_id: 'steve', amount_fraction: -.25, life_id: 'mc-life'});
assert.equal(queued.at(-1).type, 'PLAYER_HEALTH_DELTA');
world.players.get('MINECRAFT:steve').x = 40;
combat.lastHits.clear();
const beforeRanged = queued.length;
combat.hit({player_id: 'steve', target_id: 'MINDUSTRY:host', amount_fraction: .3});
assert.equal(queued.length, beforeRanged, 'a distant sword cannot hit');
combat.hit({player_id: 'steve', target_id: 'MINDUSTRY:host', amount_fraction: .3, attack_kind: 'projectile'});
assert.equal(queued.length, beforeRanged + 1, 'a bow can hit beyond melee reach');
combat.lastHits.clear(); world.players.get('MINECRAFT:steve').x = 100;
combat.hit({player_id: 'steve', target_id: 'MINDUSTRY:host', amount_fraction: .3, attack_kind: 'projectile'});
assert.equal(queued.length, beforeRanged + 1, 'projectile reach remains bounded');
world.meta.world_epoch = 21; combat.frame({seq: 1, units: []});
assert.equal(combat.units.size, 0); assert.equal(sent.at(-1).world_epoch, 21);
console.log('PASS: proportional health, host target life, reach, duplicate hits, stale frames and map epochs.');
